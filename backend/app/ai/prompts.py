# --------------------------------------------------------- сборка запросов


def _block(**fields: object) -> str:
    """Переменная часть уходит одним json-блоком: так короче, однозначнее
    и не путает модель свободным текстом."""
    return json.dumps(fields, ensure_ascii=False, indent=2)


def build_clarify_user(title: str, duration_days: int) -> str:
    return _block(goal=title, duration_days=duration_days)


def build_criteria_user(
    title: str, duration_days: int, answers: list[tuple[str, str]]
) -> str:
    return _block(
        goal=title,
        duration_days=duration_days,
        clarifications=[{"q": q, "a": a} for q, a in answers],
    )


def build_skeleton_user(
    title: str,
    duration_days: int,
    criteria: list[str],
    answers: list[tuple[str, str]],
    days_to_write: int,
) -> str:
    return _block(
        goal=title,
        duration_days=duration_days,
        criteria=criteria,
        clarifications=[{"q": q, "a": a} for q, a in answers],
        write_days_from=1,
        write_days_to=days_to_write,
    )


def build_batch_user(
    title: str,
    duration_days: int,
    criteria: list[str],
    current_phase: str,
    written_titles: list[str],
    first_day: int,
    last_day: int,
) -> str:
    return _block(
        goal=title,
        duration_days=duration_days,
        criteria=criteria,
        current_phase=current_phase,
        # Только заголовки: полные описания раздули бы вход втрое,
        # а для «не повторяйся» их достаточно.
        already_written=written_titles,
        write_days_from=first_day,
        write_days_to=last_day,
    )


def build_simplify_user(
    title: str, description: str, goal_title: str, day_number: int
) -> str:
    return _block(
        goal=goal_title,
        day_number=day_number,
        task_title=title,
        task_description=description,
    )
