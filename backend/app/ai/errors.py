"""Ошибки слоя ИИ.

Разделены намеренно: транспортная проблема и кривой ответ модели требуют
разной реакции. Первую можно повторить позже, вторую — только переспросить
сейчас, и то один раз.
"""


class AIError(Exception):
    """Базовая. Всё, что мешает получить валидный ответ."""


class AITransportError(AIError):
    """Сеть, таймаут, 5xx, исчерпан лимит провайдера."""


class AIInvalidResponse(AIError):
    """Модель ответила, но ответ не разбирается или не проходит контракт.

    В сообщении лежит текст претензии — он же уходит модели во втором
    заходе, чтобы она починила ровно то, что сломала.
    """

    def __init__(self, reason: str, raw: str | None = None) -> None:
        super().__init__(reason)
        self.reason = reason
        self.raw = raw
